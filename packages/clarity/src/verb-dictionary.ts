// TS-ahead: collocation- and role-derived verbs classify as domain when not already curated. They
// deliberately overlap other tiers and are resolved by classifyVerb's precedence, so they are NOT
// part of the disjoint-curated invariant.
const derivedDomainVerbs = new Set([
  ...allCollocationPairs().map((pair) => pair.verb.toLowerCase()),
  ...allRoleExpectedVerbs().map((verb) => verb.toLowerCase()),
]);

/**
 * Categorizes one verb, consulting the project's declared vocabulary after every built-in tier
 * that must keep its authority.
 *
 * @remarks Boolean prefixes, built-in domain verbs and generic verbs are decided first, so a
 * project cannot promote `process` or `is` by committing them to its glossary — generic stays
 * generic. What a project can do is claim a word the built-in dictionaries would score as merely
 * standard or unknown: in its domain, `fold` and `send` are domain verbs. Generic is checked
 * before standard here, which is behaviour-preserving only because the two tiers are disjoint —
 * `verb-dictionary.test.ts` asserts that, matching Java's `enforceNoOverlap`.
 */
export function classifyVerb(
  verb: string,
  vocabulary: DomainVocabulary = emptyVocabulary,
): VerbCategory {
  const lower = verb.toLowerCase();
  if (booleanPrefixes.has(lower)) return "boolean";
  if (domainVerbs.has(lower)) return "domain";
  if (genericVerbs.has(lower)) return "generic";
  if (vocabularyHasVerb(vocabulary, lower)) return "domain";
  if (standardVerbs.has(lower)) return "standard";
  if (derivedDomainVerbs.has(lower)) return "domain";
  return "unknown";
}

/**
 * The raw membership of each verb category, exposed for drift-guard invariant tests. The curated
 * tiers stay disjoint where classification is unambiguous (Generic ∩ Domain = ∅, Boolean ∩ Domain =
 * ∅); classifyVerb's precedence (boolean > domain > standard > generic) is the tie-breaker if a
 * future edit reintroduces overlap.
 */
export function verbCategoryMembers(): {
  domain: readonly string[];
  derivedDomain: readonly string[];
  standard: readonly string[];
  generic: readonly string[];
  booleanPrefixes: readonly string[];
} {
  return {
    domain: [...domainVerbs],
    // Morphologically derived (collocation/role) verbs deliberately overlap other tiers and are
    // resolved by classifyVerb's precedence — they are NOT part of the disjoint-curated invariant.
    derivedDomain: [...derivedDomainVerbs],
    standard: [...standardVerbs],
    generic: [...genericVerbs],
    booleanPrefixes: [...booleanPrefixes],
  };
}

export function verbDictionaryMetrics(): {
  domainVerbCount: number;
  standardVerbCount: number;
  genericVerbCount: number;
  booleanPrefixCount: number;
} {
  return {
    domainVerbCount: new Set([...domainVerbs.values(), ...derivedDomainVerbs.values()]).size,
    standardVerbCount: standardVerbs.size,
    genericVerbCount: genericVerbs.size,
    booleanPrefixCount: booleanPrefixes.size,
  };
}
